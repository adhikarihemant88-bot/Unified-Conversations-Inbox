CREATE TABLE locations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE agents (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  last_assigned_at timestamptz
);
CREATE INDEX agents_assignment_order
  ON agents(last_assigned_at, id);
CREATE UNIQUE INDEX agents_name_unique
  ON agents(lower(btrim(name)));

CREATE TABLE agent_assignment_lock (
  id integer PRIMARY KEY CHECK (id = 1)
);
INSERT INTO agent_assignment_lock(id) VALUES (1);

CREATE TABLE contacts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer NOT NULL REFERENCES locations(id),
  name text,
  UNIQUE (location_id, id)
);

CREATE TABLE contact_identities (
  location_id integer NOT NULL,
  contact_id integer NOT NULL,
  kind text NOT NULL CHECK (kind IN ('phone', 'email')),
  value text NOT NULL,
  PRIMARY KEY (location_id, kind, value),
  FOREIGN KEY (location_id, contact_id) REFERENCES contacts(location_id, id)
);
CREATE INDEX identities_contact ON contact_identities(location_id, contact_id);

CREATE TABLE conversations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer NOT NULL,
  participant_a_id integer NOT NULL,
  participant_b_id integer NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  assigned_to integer,
  unread_count integer NOT NULL DEFAULT 0 CHECK (unread_count >= 0),
  last_message_at timestamptz,
  last_message_id integer,
  last_message_preview text,
  CHECK (participant_a_id < participant_b_id),
  UNIQUE (location_id, participant_a_id, participant_b_id),
  UNIQUE (location_id, id),
  FOREIGN KEY (location_id, participant_a_id)
    REFERENCES contacts(location_id, id),
  FOREIGN KEY (location_id, participant_b_id)
    REFERENCES contacts(location_id, id),
  FOREIGN KEY (assigned_to) REFERENCES agents(id)
);
CREATE INDEX conversations_latest
  ON conversations(location_id, last_message_at DESC, id DESC);
CREATE INDEX conversations_filtered
  ON conversations(location_id, status, assigned_to, last_message_at DESC, id DESC);

CREATE TABLE messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer NOT NULL,
  conversation_id integer NOT NULL,
  provider_message_id text NOT NULL UNIQUE,
  channel text NOT NULL CHECK (channel IN ('sms', 'whatsapp', 'email')),
  direction text NOT NULL CHECK (direction IN ('inbound', 'outbound')),
  sender text NOT NULL,
  recipient text NOT NULL,
  body text NOT NULL,
  status text NOT NULL CHECK (status IN ('queued', 'sent', 'delivered', 'read', 'failed')),
  sent_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  FOREIGN KEY (location_id, conversation_id)
    REFERENCES conversations(location_id, id)
);
CREATE INDEX messages_history
  ON messages(location_id, conversation_id, sent_at, id);
CREATE INDEX messages_search ON messages USING gin(to_tsvector('simple', body));

CREATE TABLE provider_states (
  provider_message_id text PRIMARY KEY,
  status text NOT NULL CHECK (status IN ('queued', 'sent', 'delivered', 'read', 'failed')),
  event_at timestamptz NOT NULL,
  received_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE send_jobs (
  message_id integer PRIMARY KEY REFERENCES messages(id),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 3),
  state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'done')),
  next_attempt_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX jobs_due ON send_jobs(next_attempt_at) WHERE state = 'pending';

CREATE TABLE inbox_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer NOT NULL REFERENCES locations(id),
  type text NOT NULL,
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX events_location ON inbox_events(location_id, id);

CREATE TABLE pagination_snapshots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer NOT NULL REFERENCES locations(id),
  scope text NOT NULL,
  items jsonb NOT NULL,
  expires_at timestamptz NOT NULL DEFAULT clock_timestamp() + interval '15 minutes'
);
CREATE INDEX snapshots_expiry ON pagination_snapshots(expires_at);
